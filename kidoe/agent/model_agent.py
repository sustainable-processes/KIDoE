    def _generate_model_code(
        self,
        chem_config: dict,
        proc_config: dict,
    ) -> DataFrame:
        """
        Generate model code based on given chemistry and process configs.

        Args:
            chem_config (dict): input chemistry config
            proc_config (dict): input process config

        Returns:
            str: model code as a string
        """
        modeler = NumpyModeler()
        modeler.add_libs()

        ac_pheno = proc_config['process']['phenomenon']['accumulation']
        fp_pheno = proc_config['process']['phenomenon']['flow pattern']
        mt_phenos = proc_config['process']['phenomenon']['mass transport']
        if mt_phenos is None:
            mt_phenos = []

        ac_laws = []
        for law in self.entity['law'].values():
            if law.pheno and law.pheno == ac_pheno:
                ac_laws.append(law)
        assert len(ac_laws) == 1, f'Multiple accumulation laws: {ac_laws}'
        ac_law = next(iter(ac_laws))

        fp_var_law_dict = {}
        for var in ac_law.vars:
            for law in var.laws:
                if law.pheno and law.pheno == fp_pheno:
                    if var not in fp_var_law_dict:
                        fp_var_law_dict[var] = [law]
                    if law not in fp_var_law_dict[var]:
                        fp_var_law_dict[var].append(law)
        for var in ac_law.opt_vars:
            for law in var.laws:
                if law.pheno and law.pheno == fp_pheno:
                    if var not in fp_var_law_dict:
                        fp_var_law_dict[var] = [law]
                    if law not in fp_var_law_dict[var]:
                        fp_var_law_dict[var].append(law)
        mt_var_law_dict = {}
        for var in ac_law.opt_vars:
            for law in var.laws:
                if law.pheno and law.pheno in mt_phenos:
                    if var not in mt_var_law_dict:
                        mt_var_law_dict[var] = [law]
                    if law not in mt_var_law_dict[var]:
                        mt_var_law_dict[var].append(law)
        mt_sub_fp_var_law_dict = {}
        for mt_laws in mt_var_law_dict.values():
            for mt_law in mt_laws:
                for var in mt_law.vars:
                    for law in var.laws:
                        if law.pheno and law.pheno == fp_pheno:
                            if var not in mt_sub_fp_var_law_dict:
                                mt_sub_fp_var_law_dict[var] = [law]
                            if law not in mt_sub_fp_var_law_dict[var]:
                                mt_sub_fp_var_law_dict[var].append(law)

        assoc_ac_laws = []
        for laws in mt_var_law_dict.values():
            for law in laws:
                if law.assoc_ac_law:
                    assoc_ac_laws.append(law.assoc_ac_law)
        assert len(assoc_ac_laws) <= 1, f'Multiple associated laws: {assoc_ac_laws}'
        if assoc_ac_laws:
            assoc_ac_law = next(iter(assoc_ac_laws))
        else:
            assoc_ac_law = None

        rxn_law_dict = {}
        for rxn, rxn_phenos in chem_config['chemistry']['kinetics'].items():
            rxn_law_dict[rxn] = []
            for law in self.entity['law'].values():
                if law.pheno in rxn_phenos:
                    rxn_law_dict[rxn].append(law)

        # TODO: biphasic system
        stms = list(proc_config['process']['inlet'].keys())
        rxns = list(chem_config['chemistry']['kinetics'].keys())
        spcs = []
        spcs.extend(chem_config['chemistry']['species']['substrate'].keys())
        spcs.extend(chem_config['chemistry']['species']['reagent'].keys())
        spcs.extend(chem_config['chemistry']['species']['product'].keys())
        if chem_config['chemistry']['species']['intermediate']:
            spcs.extend(chem_config['chemistry']['species']['intermediate'].keys())
        if chem_config['chemistry']['species']['byproduct']:
            spcs.extend(chem_config['chemistry']['species']['byproduct'].keys())
        if chem_config['chemistry']['species']['side product']:
            spcs.extend(chem_config['chemistry']['species']['side product'].keys())
        nstm, nrxn, nspc = len(stms), len(rxns), len(spcs)
        dim_dict = {'stm': stms, 'rxn': rxns, 'spc': spcs}
        if ac_pheno == 'CSTR':
            assert nstm == 1, 'Only one stream is supported for `CSTR`'

        if 'num_reactors' in proc_config['process']:
            num_reactors = proc_config['process']['num_reactors']
        else:
            num_reactors = 1

        param_dict = self._read_param(chem_config, proc_config)

        n_dicts = []
        for rxn in rxns:
            if rxn not in chem_config['chemistry']['parameter']:
                continue
            rxn_dict = chem_config['chemistry']['parameter'][rxn]
            if 'Partial_Order' not in rxn_dict:
                continue
            n_dicts.extend(rxn_dict['Partial_Order'].values())
        conc_maximum = False
        if any(isinstance(d['val'], float) if 'val' in d else False for d in n_dicts):
            conc_maximum = True
        if any('min' in s and 'max' in s for s in n_dicts):
            conc_maximum = True

        self._add_model_ac_head(modeler, ac_law)
        self._add_model_param_setup(modeler, param_dict, dim_dict)
        self._add_model_conc_setup(modeler, ac_law, assoc_ac_law, conc_maximum,
                                   dim_dict)
        self._add_model_fp_laws(modeler, fp_var_law_dict)
        self._add_model_mt_sub_fp_laws(modeler, mt_sub_fp_var_law_dict, dim_dict)
        self._add_model_mt_laws(modeler, ac_law, mt_var_law_dict, dim_dict)
        self._add_model_rxn_laws(modeler, ac_law, assoc_ac_law, rxn_law_dict, dim_dict)
        self._add_model_ac_law(
            modeler,
            ac_law,
            assoc_ac_law,
            fp_var_law_dict,
            mt_var_law_dict,
            dim_dict,
        )
        self._add_model_ac_return(
            modeler,
            ac_law,
            assoc_ac_law,
            dim_dict,
        )

        self._add_simulate_head(modeler)
        self._add_simulate_param_setup(modeler, ac_law, param_dict, dim_dict)
        self._add_simulate_func(modeler, num_reactors, ac_law, assoc_ac_law, param_dict,
                                dim_dict)

        return modeler.get_code()

    def _sample_by_ensemble_ucb(
        self,
        dataset: DataFrame,
        cand_datasets: list[DataFrame],
        rmses: list[float],
        obj_dict: dict,
        num_experiments: int | None = None,
        **kwargs,
    ) -> DataFrame:
        obj_name = next(iter(obj_dict))
        maximise = obj_dict[obj_name]['target'] != 'min'
        lam = kwargs.get('lambda_std', 0.445)
        obj_name = next(iter(obj_dict.keys()))

        rmses = np.maximum(np.asarray(rmses, dtype=float), 1e-12)
        ws = rmses**-4
        ws = ws / ws.sum()

        mus = np.stack(
            [(d[f'{obj_name}(sim)'] + d[f'{obj_name}(gp mean)']).to_numpy()
             for d in cand_datasets],
            axis=1,
        )
        sigmas = np.stack([d[f'{obj_name}(gp std)'].to_numpy() for d in cand_datasets],
                          axis=1)
        mean = mus @ ws
        var = (sigmas**2 + mus**2) @ ws - mean**2
        std = np.sqrt(np.maximum(var, 0.0))

        ens = cand_datasets[0].copy()
        ens['ensemble'] = mean + lam * std if maximise else mean - lam * std
        ens = ens.sort_values('ensemble', ascending=not maximise)
        return ens[:num_experiments] if num_experiments else ens

    @staticmethod
    def _hv_improvement(front: np.ndarray, Y: np.ndarray,
                        ref_point: np.ndarray) -> np.ndarray:
        m = front.shape[1]
        partitioning = NondominatedPartitioning(
            ref_point=torch.as_tensor(ref_point, dtype=torch.double),
            Y=torch.as_tensor(front, dtype=torch.double),
        )
        lower, upper = (b.numpy() for b in partitioning.get_hypercell_bounds())
        n_cells = lower.shape[0]

        flat = Y.reshape(-1, m)
        hvi = np.empty(len(flat))
        chunk = max(1, 2**22 // max(1, n_cells * m))
        for start in range(0, len(flat), chunk):
            y = flat[start:start + chunk, np.newaxis, :]
            overlap = np.clip(np.minimum(y, upper) - lower, 0.0, None)
            hvi[start:start + chunk] = overlap.prod(axis=-1).sum(axis=-1)
        return hvi.reshape(Y.shape[:-1])

    def _sample_by_ensemble_qnehvi(
        self,
        dataset: DataFrame,
        cand_datasets: list[DataFrame],
        rmses: list[float],
        obj_dict: dict,
        num_experiments: int | None = None,
        **kwargs,
    ) -> DataFrame:
        rng = np.random.Generator(np.random.PCG64())
        lam = kwargs.get('lambda_std', 0.445)
        obj_names = list(obj_dict.keys())
        signs = np.array(
            [-1.0 if obj_dict[name]['target'] == 'min' else 1.0 for name in obj_names])
        front = dataset[obj_names].to_numpy(dtype=float) * signs
        ref_point = front.min(axis=0)

        ws = np.array([1 / rmse**4 for rmse in rmses])
        ws = ws / ws.sum()
        ehvis = []
        for d in cand_datasets:
            mean = np.stack(
                [(d[f'{n}(sim)'] + d[f'{n}(gp mean)']).to_numpy() for n in obj_names],
                axis=-1,
            )
            std = np.stack([d[f'{n}(gp std)'].to_numpy() for n in obj_names], axis=-1)
            noise = rng.standard_normal((len(d), self.num_sample, len(obj_names)))
            samples = (mean[:, None, :] + std[:, None, :] * noise * lam) * signs
            ehvis.append(self._hv_improvement(front, samples, ref_point).mean(axis=1))
        ehvi = np.stack(ehvis, axis=1) @ ws
        ens = cand_datasets[0].copy()
        ens = ens[[col for col in ens.columns if col in dataset.columns]]
        ens['ehvi'] = ehvi.tolist()
        ens = ens.sort_values('ehvi', ascending=False)
        return ens[:num_experiments] if num_experiments else ens

