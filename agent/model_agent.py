    def _extract_cal_param(self, chem_config: Dict, proc_config: Dict) -> Dict:
        chem_config = deepcopy(chem_config)
        proc_config = deepcopy(proc_config)
        chem_param_dict = self._extract_chem_param(chem_config)
        proc_param_dict = self._extract_proc_param(proc_config)
        param_dict = {}
        for k, v in chem_param_dict.items():
            if isinstance(v, dict) and 'min' in v and 'max' in v:
                param_dict[k] = v
        for k, v in proc_param_dict.items():
            if isinstance(v, dict) and 'min' in v and 'max' in v:
                param_dict[k] = v
        return param_dict

    def _extract_param(self, chem_config: Dict, proc_config: Dict) -> Dict:
        chem_param_dict = self._extract_chem_param(chem_config)
        proc_param_dict = self._extract_proc_param(proc_config)
        oper_param_dict = self._extract_proc_oper_param(proc_config)
        param_dict = {}
        param_dict.update(chem_param_dict)
        param_dict.update(proc_param_dict)
        param_dict.update(oper_param_dict)
        return param_dict

    def _extract_param_val(self, chem_config: Dict, proc_config: Dict) -> Dict:
        chem_param_dict = self._extract_chem_param(chem_config)
        proc_param_dict = self._extract_proc_param(proc_config)
        oper_param_dict = self._extract_proc_oper_param(proc_config)
        param_dict = {}
        for k, v in chem_param_dict.items():
            if isinstance(v, (int, float)):
                param_dict[k] = v
            if isinstance(v, dict):
                if 'val' in v:
                    param_dict[k] = v['val']
                else:
                    param_dict[k] = None
        for k, v in proc_param_dict.items():
            if isinstance(v, (int, float)):
                param_dict[k] = v
            if isinstance(v, dict):
                if 'val' in v:
                    param_dict[k] = v['val']
                else:
                    param_dict[k] = None
        for k, v in oper_param_dict.items():
            param_dict[k] = None
        return param_dict

    def _write_cal_params(
        self, cal_param_dict: Dict, chem_config: Dict, proc_config: Dict
    ) -> Tuple[Dict, Dict]:
        """Write calibrated parameter values back to configuration dictionaries.

        This method updates the chemistry and process configuration dictionaries
        with calibrated parameter values from the calibration results.

        Args:
            cal_param_dict (Dict): Calibrated parameter dictionary
            chem_config (Dict): Chemistry configuration to update
            proc_config (Dict): Process configuration to update

        Returns:
            Tuple[Dict, Dict]: Updated chemistry and process configurations
        """
        chem_config = deepcopy(chem_config)
        proc_config = deepcopy(proc_config)
        for key, val in cal_param_dict.items():
            param_name, gas_or_solid, stm, rxn, spc = key

            if rxn:
                chem_rxn_config = chem_config['chemistry']['parameter'][rxn]
                param_dims = set(self.entity['var'][param_name]['dims'])
                if param_dims == set(['Reaction']):
                    chem_rxn_config[param_name] = val
                if param_dims == set(['Reaction', 'Species']):
                    chem_rxn_config[param_name][spc] = val
                if param_dims == set(['Stream', 'Reaction']) and stm:
                    chem_rxn_config[param_name][stm] = val
                chem_config['chemistry']['parameter'][rxn] = chem_rxn_config

            for sec in ['structure', 'physics', 'mass transport']:
                if sec not in proc_config['process']['parameter']:
                    continue
                if param_name not in proc_config['process']['parameter'][sec]:
                    continue
                proc_sec_config = proc_config['process']['parameter'][sec]
                param_dims = set(self.entity['var'][param_name]['dims'])
                if param_dims == set([]):
                    proc_sec_config[param_name] = val
                if param_dims == set(['Species']):
                    proc_sec_config[param_name][spc] = val
                if param_dims == set(['Stream']):
                    proc_sec_config[param_name][stm] = val
                elif param_dims == set(['Stream', 'Species']):
                    proc_sec_config[param_name][stm][spc] = val
                proc_config['process']['parameter'][sec] = proc_sec_config

        return chem_config, proc_config

    def _generate_model_code(
        self,
        chem_config: Dict,
        proc_config: Dict,
        fast_reaction: bool = False,
        njit: bool = False,
    ) -> DataFrame:
        """
        Generate model code based on given chemistry and process configs.

        Args:
            chem_config (Dict): input chemistry config
            proc_config (Dict): input process config

        Returns:
            str: model code as a string
        """
        modeler = NumpyModeler()
        modeler.add_libs()

        ac_pheno = proc_config['process']['phenomenon']['accumulation']
        fp_pheno = proc_config['process']['phenomenon']['flow pattern']
        mt_phenos = proc_config['process']['phenomenon']['mass transport']

        ac_laws = []
        for law, law_dict in self.entity['law'].items():
            if law_dict['pheno'] == ac_pheno:
                ac_laws.append(law)
        ac_law = ac_laws[0]

        fp_param_law_dict = {}
        for param in self.entity['law'][ac_law]['vars']:
            for param_law in self.entity['var'][param]['laws']:
                if self.entity['law'][param_law]['pheno'] == fp_pheno:
                    if param not in fp_param_law_dict:
                        fp_param_law_dict[param] = [param_law]
                    if param_law not in fp_param_law_dict[param]:
                        fp_param_law_dict[param].append(param_law)

        mt_param_law_dict = {}
        for param in self.entity['law'][ac_law]['opt_vars']:
            for param_law in self.entity['var'][param]['laws']:
                if self.entity['law'][param_law]['pheno'] in mt_phenos:
                    if param not in mt_param_law_dict:
                        mt_param_law_dict[param] = [param_law]
                    if param_law not in mt_param_law_dict[param]:
                        mt_param_law_dict[param].append(param_law)

        mt_sub_fp_param_law_dict = {}
        for mt_laws in mt_param_law_dict.values():
            for mt_law in mt_laws:
                for param in self.entity['law'][mt_law]['vars']:
                    for param_law in self.entity['var'][param]['laws']:
                        if self.entity['law'][param_law]['pheno'] == fp_pheno:
                            if param not in mt_sub_fp_param_law_dict:
                                mt_sub_fp_param_law_dict[param] = [param_law]
                            if param_law not in mt_sub_fp_param_law_dict[param]:
                                mt_sub_fp_param_law_dict[param].append(param_law)

        int_ac_laws = []
        for law in [law for laws in mt_param_law_dict.values() for law in laws]:
            if self.entity['law'][law]['int_fml']:
                int_ac_laws.append(law)
        if int_ac_laws:
            int_ac_law = int_ac_laws[0]
        else:
            int_ac_law = None

        rxn_law_dict = {}
        for rxn, rxn_phenos in chem_config['chemistry']['kinetics'].items():
            rxn_law_dict[rxn] = []
            for law, law_dict in self.entity['law'].items():
                if law_dict['pheno'] in rxn_phenos:
                    rxn_law_dict[rxn].append(law)

        # TODO: biphasic system
        stms = list(proc_config['process']['inlet'].keys())
        rxns = list(chem_config['chemistry']['kinetics'].keys())
        spcs = []
        spcs.extend(chem_config['chemistry']['species']['reagents'].keys())
        spcs.extend(chem_config['chemistry']['species']['products'].keys())
        if chem_config['chemistry']['species']['intermediates']:
            spcs.extend(chem_config['chemistry']['species']['intermediates'].keys())
        if chem_config['chemistry']['species']['byproducts']:
            spcs.extend(chem_config['chemistry']['species']['byproducts'].keys())
        if chem_config['chemistry']['species']['side products']:
            spcs.extend(chem_config['chemistry']['species']['side products'].keys())

        param_dict = self._extract_param(chem_config, proc_config)
        param_inds = list(param_dict.keys())

        # derivative / delta head
        if ac_pheno == 'Continuous':
            diff_var = self.entity['law'][ac_law]['diff_var']
            diff_ul = self.entity['law'][ac_law]['diff_ul']
            diff_iv = self.entity['law'][ac_law]['diff_iv']
            diff_sym = MMLExpression(self.entity['var'][diff_var]['sym']).to_numpy()
            if njit:
                modeler.add_code('\n@njit(cache=True)', 0)
            modeler.add_code(f'def derivative({diff_sym}, _c, p):', 0)
        if ac_pheno == 'CSTR':
            modeler.add_code('\ndef delta(c, p):', 0)

        # parameter setup
        modeler.add_code('# parameter setup', 1)
        vars = list(set(k[0] for k in param_inds))
        for var in vars:
            sym = MMLExpression(self.entity['var'][var]['sym']).to_numpy()
            dims = self.entity['var'][var]['dims']
            if set(dims) == set([]):
                ind = (var, None, None, None, None)
                modeler.add_code(f'{sym} = p[{param_inds.index(ind)}]', 1)
            if set(dims) == set(['Stream']):
                modeler.add_code(f'{sym} = np.zeros('
                                 f'{len(stms),}, dtype=np.float64)', 1)
                for i, stm in enumerate(stms):
                    ind = (var, None, stm, None, None)
                    if ind in param_inds:
                        modeler.add_code(f'{sym}[{i}] = '
                                         f'p[{param_inds.index(ind)}]', 1)
            if set(dims) == set(['Reaction']):
                modeler.add_code(
                    f'{sym} = np.zeros('
                    f'{len(rxns),}, dtype=np.float64)', 1)
                for i, rxn in enumerate(rxns):
                    ind = (var, None, None, rxn, None)
                    if ind in param_inds:
                        modeler.add_code(f'{sym}[{i}] = '
                                         f'p[{param_inds.index(ind)}]', 1)
            if set(dims) == set(['Species']):
                modeler.add_code(
                    f'{sym} = np.zeros('
                    f'{len(spcs),}, dtype=np.float64)', 1)
                for i, spc in enumerate(spcs):
                    ind = (var, None, None, None, spc)
                    if ind in param_inds:
                        modeler.add_code(f'{sym}[{i}] = '
                                         f'p[{param_inds.index(ind)}]', 1)
            if set(dims) == set(['Stream', 'Reaction']):
                modeler.add_code(
                    f'{sym} = np.zeros('
                    f'{len(stms), len(rxns)}, dtype=np.float64)', 1)
                for i, stm in enumerate(stms):
                    for j, rxn in enumerate(rxns):
                        ind = (var, None, stm, rxn, None)
                        if ind in param_inds:
                            modeler.add_code(
                                f'{sym}[{i},{j}] = p[{param_inds.index(ind)}]', 1)
            if set(dims) == set(['Stream', 'Species']):
                modeler.add_code(
                    f'{sym} = np.zeros('
                    f'{len(stms), len(spcs)}, dtype=np.float64)', 1)
                for i, stm in enumerate(stms):
                    for j, spc in enumerate(spcs):
                        ind = (var, None, stm, None, spc)
                        if ind in param_inds:
                            modeler.add_code(
                                f'{sym}[{i},{j}] = p[{param_inds.index(ind)}]', 1)
            if set(dims) == set(['Reaction', 'Species']):
                modeler.add_code(
                    f'{sym} = np.zeros('
                    f'{len(rxns), len(spcs)}, dtype=np.float64)', 1)
                for i, rxn in enumerate(rxns):
                    for j, spc in enumerate(spcs):
                        ind = (var, None, None, rxn, spc)
                        if ind in param_inds:
                            modeler.add_code(
                                f'{sym}[{i},{j}] = '
                                f'p[{param_inds.index(ind)}]', 1)

            unit = self.entity['var'][var]['unit']
            if unit:
                mtr = self.entity['unit'][unit]['mtr']
                rto = self.entity['unit'][unit]['rto']
                intcpt = self.entity['unit'][unit]['intcpt']
                if mtr and rto:
                    modeler.add_code(f'{sym} *= {rto}', 1)
                if mtr and intcpt:
                    modeler.add_code(f'{sym} += {intcpt}', 1)
        modeler.add_code('', 0)

        # concentration setup
        modeler.add_code('# concentration setup', 1)
        if ac_pheno == 'Continuous':
            if int_ac_law:
                modeler.add_code(f'c = np.zeros({len(stms), 2*len(spcs)}, '
                                 'dtype=np.float64)', 1)
                modeler.add_code(f'for i in range({len(stms)}):', 1)
                modeler.add_code(f'c[i] = _c[i*{2*len(spcs)}:(i+1)*{2*len(spcs)}]', 2)
            else:
                modeler.add_code(f'c = np.zeros({len(stms), len(spcs)}, '
                                 'dtype=np.float64)', 1)
                modeler.add_code(f'for i in range({len(stms)}):', 1)
                modeler.add_code(f'c[i] = _c[i*{len(spcs)}:(i+1)*{len(spcs)}]', 2)
        else:
            modeler.add_code(f'c = c.reshape({len(stms), 2*len(spcs)})', 1)
        modeler.add_code('', 0)

        # flow pattern
        modeler.add_code('# flow pattern', 1)
        for var, laws in fp_param_law_dict.items():
            for law in laws:
                law_vars = self.entity['law'][law]['vars']
                law_syms = [self.entity['var'][var]['sym'] for var in law_vars]
                law_syms = [MMLExpression(sym).to_numpy() for sym in law_syms]
                sym = MMLExpression(self.entity['var'][var]['sym']).to_numpy()
                code = MMLExpression(self.entity['law'][law]['fml']).to_numpy()
            if '\n' in code:
                func_head = modeler.add_func(var, law_syms, code, 1)
                modeler.add_code(f'{sym} = {func_head}', 1)
            else:
                modeler.add_code(f'{sym} = {code}', 1)
            modeler.add_code('', 0)

        # mass transfer sub flow pattern
        modeler.add_code('# mass transfer sub flow pattern', 1)
        for var, laws in mt_sub_fp_param_law_dict.items():
            for law in laws:
                law_vars = self.entity['law'][law]['vars']
                law_syms = [self.entity['var'][var]['sym'] for var in law_vars]
                law_syms = [MMLExpression(sym).to_numpy() for sym in law_syms]
                sym = MMLExpression(self.entity['var'][var]['sym']).to_numpy()
                code = MMLExpression(self.entity['law'][law]['fml']).to_numpy()
                modeler.add_code(f'{sym} = {code}', 1)
                # modeler.add_code(
                #     f'{sym} = np.zeros('
                #     f'{len(stms), len(spcs)}, dtype=np.float64)', 1)
                # func_head = modeler.add_func(var, law_syms, code, 1)
                # for i, spc in enumerate(spcs):
                #     spc_func_head = func_head
                #     for law_var in law_vars:
                #         law_var_dims = self.entity['var'][law_var]['dims']
