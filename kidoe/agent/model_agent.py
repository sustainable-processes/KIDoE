class NumpyModeler:
    """Modeler for constructing numpy models."""

    def __init__(self, ntab: int = 4):
        self.ntab = ntab
        self.code = []

    def add_libs(self):
        self.add_code('import warnings', 0)
        self.add_code('warnings.filterwarnings("ignore", '
                      'message="The iteration is not making good progress")\n', 0)
        self.add_code('import functools', 0)
        self.add_code('import numpy as np', 0)
        self.add_code('import pandas as pd', 0)
        self.add_code('from numba import njit', 0)
        self.add_code('from scipy.integrate import solve_bvp, solve_ivp', 0)
        self.add_code('from scipy.optimize import differential_evolution, fsolve', 0)
        self.add_code('', 0)

    def add_code(self, code: str | list[str], level: int):
        if isinstance(code, str):
            self.code.append(' ' * self.ntab * level + code)
        if isinstance(code, list) and all(isinstance(c, str) for c in code):
            for c in code:
                self.code.append(' ' * self.ntab * level + c)

    def add_func(self, obj: str, syms: list[str], code: str, level: int) -> str:
        code = code.split('\n')
        if '=' not in code[0] and ':' not in code[0]:
            code = code[1:] + code[:1]
        obj = obj.lower().replace('-', '_')
        func_head = f'calc_{obj}'
        self.add_code(f'def {func_head}({", ".join(syms)}):', level)
        self.add_code(code[:-1], level + 1)
        self.add_code(f'return {code[-1]}', level + 1)
        return func_head

    def get_code(self) -> str:
        return '\n'.join(self.code)


class ModelAgent:
    """Model agent for simulating and calibrating models.

    Phenomena are inferred from given ones based on the Model Ontology.
    Parameters are also generated by navigating the Model Ontology.
    """

    def __init__(
        self,
        err: str = 'rmse',
        maxiter: int = 100,
        njit: bool = True,
        high_prec: bool = False,
    ):
        super().__init__()
        assert err in ['rmse', 'rmsre'], f'Unsupported error fun: {err}'
        self.err = err
        self.maxiter = maxiter
        self.njit = njit
        self.high_prec = high_prec
        if high_prec:
            self.rtol, self.atol = 1e-10, 1e-12
        else:
            self.rtol, self.atol = 1e-6, 1e-9
        ontomo_path = os.path.join(os.path.abspath(__file__),
                                   '../../ontology/OntoMo.owl')
        self.ontomo = KnowledgeGraphAgent(ontomo_path)
        self.entity = self.ontomo.query()
        self.num_pts = 21
        self.num_sample = 100
        self.acq_func_dict = {
            'ensemble_ucb': self._sample_by_ensemble_ucb,
            'ensemble_qnehvi': self._sample_by_ensemble_qnehvi,
        }

    def _read_chem_param(self, chem_config: dict) -> dict:
        param_dict = {}

        rxns = []
        rxns.extend(chem_config['chemistry']['reaction']['main'])
        if chem_config['chemistry']['reaction']['side']:
            rxns.extend(chem_config['chemistry']['reaction']['side'])

        for rxn in rxns:
            lhs = rxn.split(' > ', maxsplit=1)[0]
            rhs = rxn.split(' > ', maxsplit=1)[1]
            lhs_spcs = [s.split(' ')[-1] for s in lhs.split(' + ')]
            rhs_spcs = [s.split(' ')[-1] for s in rhs.split(' + ')]
            for s in lhs.split(' + '):
                if re.match(r'^\d+$', s.split(' ')[0]):
                    val = {'unit': None, 'val': -float(s.split(' ')[0])}
                    spc = s.split(' ')[1]
                else:
                    val = {'unit': None, 'val': -1.0}
                    spc = s
                key = ('Stoichiometric_Coefficient', None, None, rxn, spc)
                if spc in rhs_spcs:
                    continue
                param_dict[key] = val
            for s in rhs.split(' + '):
                if re.match(r'^\d+$', s.split(' ')[0]):
                    val = {'unit': None, 'val': float(s.split(' ')[0])}
                    spc = s.split(' ')[1]
                else:
                    val = {'unit': None, 'val': 1.0}
                    spc = s
                key = ('Stoichiometric_Coefficient', None, None, rxn, spc)
                if spc in lhs_spcs:
                    continue
                param_dict[key] = val

        if 'constant' in chem_config['chemistry']['parameter']:
            config_const_dict = chem_config['chemistry']['parameter']['constant']
            if config_const_dict:
                for param in config_const_dict:
                    ind = (param, None, None, None, None)
                    val = config_const_dict[param]['val']
                    param_dict[ind] = val

        for rxn in rxns:
            if rxn not in chem_config['chemistry']['parameter']:
                continue
            config_rxn_dict = chem_config['chemistry']['parameter'][rxn]
            for v in config_rxn_dict:
                var = self.entity['var'][v]
                if set(var.dims) == set(['Reaction']):
                    ind = (v, None, None, rxn, None)
                    val = config_rxn_dict[var]
                    param_dict[ind] = val
                if set(var.dims) == set(['Reaction', 'Species']):
                    for spc in config_rxn_dict[var]:
                        ind = (v, None, None, rxn, spc)
                        val = config_rxn_dict[var][spc]
                        param_dict[ind] = val
                if set(var.dims) == set(['Stream', 'Reaction']):
                    for stm in config_rxn_dict[var]:
                        ind = (v, None, stm, rxn, None)
                        val = config_rxn_dict[var][stm]
                        param_dict[ind] = val

        param_dict = dict(sorted(param_dict.items()))
        return param_dict

    def _read_proc_param(self, proc_config: dict) -> dict:
        param_dict = {}
        for sec in ['structure', 'physics', 'mass transport', 'flow']:
            if sec not in proc_config['process']['parameter']:
                continue
            config_sec_dict = proc_config['process']['parameter'][sec]
            for v in config_sec_dict:
                var = self.entity['var'][v]
                if set(var.dims) == set([]):
                    ind = (v, None, None, None, None)
                    val = config_sec_dict[v]
                    param_dict[ind] = val
                if set(var.dims) == set(['Species']):
                    for spc in config_sec_dict[v]:
                        ind = (v, None, None, None, spc)
                        val = config_sec_dict[v][spc]
                        param_dict[ind] = val
                if set(var.dims) == set(['Stream']):
                    for stm in config_sec_dict[v]:
                        ind = (v, None, stm, None, None)
                        val = config_sec_dict[v][stm]
                        param_dict[ind] = val
                if set(var.dims) == set(['Stream', 'Species']):
                    for stm in config_sec_dict[v]:
                        for spc in config_sec_dict[v][stm]:
                            ind = (v, None, stm, None, spc)
                            val = config_sec_dict[v][stm][spc]
                            param_dict[ind] = val
        param_dict = dict(sorted(param_dict.items()))
        return param_dict

    def _read_oper_param(self, proc_config: dict) -> dict:
        param_dict = {}
        config_oper_dict = proc_config['process']['parameter']['operation']
        for v in config_oper_dict:
            var = self.entity['var'][v]
            if set(var.dims) == set([]):
                ind = (v, None, None, None, None)
                val = config_oper_dict[var]
                param_dict[ind] = val
            if set(var.dims) == set(['Stream']):
                for stm in config_oper_dict[var]:
                    ind = (v, None, stm, None, None)
                    val = config_oper_dict[var][stm]
