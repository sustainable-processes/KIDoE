    def _add_model_fp_laws(self, modeler: NumpyModeler, fp_var_law_dict: dict):
        modeler.add_code('# flow pattern', 1)
        law_flag = False
        for var, laws in fp_var_law_dict.items():
            for law in laws:
                law_flag = True
                lsyms = [MMLExpr(lvar.sym).to_numpy() for lvar in law.vars]
                sym = MMLExpr(var.sym).to_numpy()
                code = MMLExpr(law.fml).to_numpy()
                if '\n' in code:
                    func_head = modeler.add_func(var.name, lsyms, code, 1)
                    modeler.add_code(f'{sym} = {func_head}({", ".join(lsyms)})', 1)
                else:
                    modeler.add_code(f'{sym} = {code}', 1)
            modeler.add_code('', 0)
        if not law_flag:
            modeler.add_code('', 0)

    def _add_model_mt_sub_fp_laws(self, modeler: NumpyModeler,
                                  mt_sub_fp_var_law_dict: dict, dim_dict: dict):
        nstm, nspc = len(dim_dict['stm']), len(dim_dict['spc'])
        modeler.add_code('# mass transfer sub flow pattern', 1)
