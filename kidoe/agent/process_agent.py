import os
import shutil
import sys
from copy import deepcopy
from typing import Dict

import yaml

from .knowledge_graph_agent import KnowledgeGraphAgent


class ProcessAgent:
    """Process agent for generating process configurations.
    
    Phenomena are candidate observations defined in the Model Ontology.
    Parameters are generated by navigating the Model Ontology graph.

    Example:
        # TODO
    """

    def __init__(self):
        super().__init__()
        ontomo_path = os.path.join(os.path.abspath(__file__),
                                   '../../ontology/OntoMo.owl')
        self.ontomo = KnowledgeGraphAgent(ontomo_path)
        self.entity = self.ontomo.query()

    def parameterize(self, proc_config: Dict, chem_config: Dict) -> Dict:
        """Parameterize process configuration based on the Model Ontology.

        Args:
            proc_config (Dict): Process configuration containing defined phenomena
            chem_config (Dict): Base chemistry configuration

        Returns:
            Dict: Updated process configuration with parameters
        """
        ac_pheno = proc_config['process']['phenomenon']['accumulation']

        fp_phenos = proc_config['process']['phenomenon']['flow pattern']
        if isinstance(fp_phenos, str):
            fp_phenos = [fp_phenos]

        mt_phenos = proc_config['process']['phenomenon']['mass transport']
        if isinstance(mt_phenos, str):
            mt_phenos = [mt_phenos]

        ac_fp_phenos = self.entity['pheno'][ac_pheno].fps
        fp_phenos = [pheno for pheno in fp_phenos if pheno in ac_fp_phenos]
        fp_mt_phenos = []
        for fp_pheno in fp_phenos:
            for mt_pheno in self.entity['pheno'][fp_pheno].mts:
                if mt_pheno not in fp_mt_phenos:
                    fp_mt_phenos.append(mt_pheno)
        mt_phenos = [pheno for pheno in mt_phenos if pheno in fp_mt_phenos]

        ac_laws = []
        for law in self.entity['law'].values():
            if law.pheno and law.pheno == ac_pheno:
                ac_laws.append(law)
        assert len(ac_laws) == 1, f'Multiple accumulation laws: {ac_laws}'
        ac_law = next(iter(ac_laws))

        fp_var_law_dict = {}
        for var in ac_law.vars:
            for law in var.laws:
                if law.pheno and law.pheno in fp_phenos:
                    if var not in fp_var_law_dict:
                        fp_var_law_dict[var] = [law]
                    if law not in fp_var_law_dict[var]:
                        fp_var_law_dict[var].append(law)
        for var in ac_law.opt_vars:
            for law in var.laws:
                if law.pheno and law.pheno in fp_phenos:
                    if var not in fp_var_law_dict:
                        fp_var_law_dict[var] = [law]
                    if law not in fp_var_law_dict[var]:
                        fp_var_law_dict[var].append(law)
        mt_var_law_dict = {}
        for var in ac_law.opt_vars:
            for law in var.laws:
                if law.pheno and law.pheno in mt_phenos:
                    if var not in mt_var_law_dict:
                        mt_var_law_dict[var] = [law]
                    if law not in mt_var_law_dict[var]:
                        mt_var_law_dict[var].append(law)
        mt_sub_fp_var_law_dict = {}
        for mt_laws in mt_var_law_dict.values():
            for mt_law in mt_laws:
                for var in mt_law.vars:
                    for law in var.laws:
                        if law.pheno and law.pheno in fp_phenos:
                            if var not in mt_sub_fp_var_law_dict:
                                mt_sub_fp_var_law_dict[var] = [law]
                            if law not in mt_sub_fp_var_law_dict[var]:
                                mt_sub_fp_var_law_dict[var].append(law)

        # TODO: biphasic system
        substrates = list(chem_config['chemistry']['species']['substrate'].keys())
        reagents = list(chem_config['chemistry']['species']['reagent'].keys())
        products = list(chem_config['chemistry']['species']['product'].keys())
        spcs = [
            spc for role in chem_config['chemistry']['species']
            if chem_config['chemistry']['species'][role]
            for spc in chem_config['chemistry']['species'][role]
        ]
        stms = list(proc_config['process']['inlet'].keys())
        listed_laws = []
        listed_laws.append(ac_law)
        for laws in fp_var_law_dict.values():
            listed_laws.extend(laws)
        for laws in mt_var_law_dict.values():
            listed_laws.extend(laws)
        for laws in mt_sub_fp_var_law_dict.values():
            listed_laws.extend(laws)
        vars = []
        for law in listed_laws:
            for var in law.vars:
                if var.cls == 'StateVariable':
                    continue
                if var not in vars:
                    vars.append(var)
        if self.entity['var']['Temperature'] not in vars:
            vars.append(self.entity['var']['Temperature'])

        proc_config['process']['parameter'] = {}
        for var_cls in ['Structure', 'Physics', 'MassTransport', 'Flow']:
            sec = ''.join([' ' + c.lower() if c.isupper() else c for c in var_cls])
            sec = sec.strip()
            for var in vars:
                if var.laws:
                    continue
                if var.cls == f'{var_cls}Parameter':
                    if sec not in proc_config['process']['parameter']:
                        proc_config['process']['parameter'][sec] = {}
                    config_param_dict = {}
                    if set(var.dims) == set([]):
                        config_param_dict = {'unit': var.unit, 'val': None}
                    if set(var.dims) == set(['Species']):
                        for spc in spcs:
                            config_param_dict[spc] = {'unit': var.unit, 'val': None}
                    if set(var.dims) == set(['Stream', 'Species']):
                        for stm in stms:
                            config_param_dict[stm] = {}
                            for spc in spcs:
                                config_param_dict[stm][spc] = {
                                    'unit': var.unit,
                                    'val': None,
                                }
                    proc_config['process']['parameter'][sec][var] = config_param_dict

        sec = 'operation'
        for var in vars:
            if var.laws:
                continue
            config_param_dict = {}
            if var.cls == 'OperationParameter':
                if sec not in proc_config['process']['parameter']:
                    proc_config['process']['parameter'][sec] = {}
                config_param_dict = {}
                if set(var.dims) == set([]):
                    config_param_dict = {'unit': var.unit, 'transform': None}
                if set(var.dims) == set(['Stream']):
                    for stm in stms:
                        config_param_dict[stm] = {'unit': var.unit, 'transform': None}
                if set(var.dims) == set(['Stream', 'Species']):
                    for stm in stms:
                        config_param_dict[stm] = {}
                        for spc in proc_config['process']['inlet'][stm]['solute']:
                            config_param_dict[stm][spc] = {
                                'unit': var.unit,
                                'transform': None,
                            }
                proc_config['process']['parameter'][sec][var] = config_param_dict
        proc_config['process']['parameter']['design'] = None

        sec = 'measure'
        param = 'Outlet_Concentration'
        proc_config['process']['parameter'][sec] = {}
        config_param_dict = {}
        for stm in stms:
            config_param_dict[stm] = {}
            for spc in products:
                config_param_dict[stm][spc] = {'unit': 'mol_per_L', 'name': None}
        proc_config['process']['parameter']['measure'][param] = config_param_dict
        proc_config['process']['algorithm'] = {'acquisition': None}
        proc_config['process']['objective'] = {
            'yield': {
                'transform': None,
                'target': 'max'
            }
        }

        proc_config['file type'] = 'proc parameterized'
        return proc_config

    def parameterize_and_dump(self, in_proc_cfg_path: str, chem_cfg_path: str,
                              out_proc_cfg_path: str):
        """Load configuration files, parameterize, and save the result.

        Reads process and chemistry configuration files, generates process 
        parameters using the Model Ontology, and writes the parameterized 
        configuration to an output file.

        Args:
            in_proc_cfg_path (str): Path to input process configuration file
            chem_cfg_path (str): Path to input chemistry configuration file
            out_proc_cfg_path (str): Path to output parameterized process 
                                     configuration file
        """
        with open(in_proc_cfg_path, 'r') as f:
            proc_config = yaml.load(f, yaml.FullLoader)
        with open(chem_cfg_path, 'r') as f:
            chem_config = yaml.load(f, yaml.FullLoader)
        proc_config = self.parameterize(proc_config, chem_config)
        with open(out_proc_cfg_path, 'w') as f:
            yaml.dump(proc_config, f, sort_keys=False)

    def generate_and_dump(self, in_proc_cfg_path: str, out_proc_dir: str):
        """Generate and save candidate process configurations.

        This method generates multiple candidate process configurations by enumerating
        all valid phenomenon combinations using the Model Ontology. Each candidate 
        configuration contains only parameters relevant to that combination.

        Args:
            in_proc_cfg_path (str): Path to input process configuration file
            out_proc_dir (str): Directory where candidate configurations will be saved
        """
        if os.path.exists(out_proc_dir):
            while True:
                delete_flag = input(f'Delete files in "{out_proc_dir}"? (y/n)')
                if delete_flag in ['Y', 'y', '']:
                    for filename in os.listdir(out_proc_dir):
                        file_path = os.path.join(out_proc_dir, filename)
                        if os.path.isfile(file_path) or os.path.islink(file_path):
                            os.unlink(file_path)
                        elif os.path.isdir(file_path):
                            shutil.rmtree(file_path)
                    break
                elif delete_flag in ['N', 'n']:
                    sys.exit(0)
        else:
            os.mkdir(out_proc_dir)

        with open(in_proc_cfg_path, 'r') as f:
            config = yaml.load(f, yaml.FullLoader)
        ac_pheno = config['process']['phenomenon']['accumulation']
        fp_phenos = config['process']['phenomenon']['flow pattern']
        if isinstance(fp_phenos, str):
            fp_phenos = [fp_phenos]
        mt_phenos = config['process']['phenomenon']['mass transport']
        if isinstance(mt_phenos, str):
            mt_phenos = [mt_phenos]

        ac_fp_phenos = self.entity['pheno'][ac_pheno].fps
        fp_phenos = [pheno for pheno in fp_phenos if pheno in ac_fp_phenos]

        ac_laws = []
        for law in self.entity['law'].values():
            if law.pheno and law.pheno == ac_pheno:
                ac_laws.append(law)
        assert len(ac_laws) == 1, f'Multiple accumulation laws: {ac_laws}'
        ac_law = next(iter(ac_laws))

        cand_idx = 0
        for sel_fp_pheno in fp_phenos:
            for sel_mt_pheno in mt_phenos:
                if sel_mt_pheno not in self.entity['pheno'][sel_fp_pheno].mts:
                    continue
                sel_mt_phenos = [sel_mt_pheno]
                cand_config = deepcopy(config)
                cand_config['process']['phenomenon']['flow pattern'] = sel_fp_pheno
                cand_config['process']['phenomenon']['mass transport'] = sel_mt_phenos

                fp_var_law_dict = {}
                for var in ac_law.vars:
                    for law in var.laws:
                        if law.pheno and law.pheno == sel_fp_pheno:
                            if var not in fp_var_law_dict:
                                fp_var_law_dict[var] = [law]
                            if law not in fp_var_law_dict[var]:
                                fp_var_law_dict[var].append(law)
                for var in ac_law.opt_vars:
                    for law in var.laws:
                        if law.pheno and law.pheno == sel_fp_pheno:
                            if var not in fp_var_law_dict:
                                fp_var_law_dict[var] = [law]
                            if law not in fp_var_law_dict[var]:
                                fp_var_law_dict[var].append(law)
                mt_var_law_dict = {}
                for var in ac_law.opt_vars:
                    for law in var.laws:
                        if law.pheno and sel_mt_phenos and law.pheno in sel_mt_phenos:
                            if var not in mt_var_law_dict:
                                mt_var_law_dict[var] = [law]
                            if law not in mt_var_law_dict[var]:
                                mt_var_law_dict[var].append(law)
                mt_sub_fp_var_law_dict = {}
                for mt_laws in mt_var_law_dict.values():
                    for mt_law in mt_laws:
                        for var in mt_law.vars:
                            for law in var.laws:
                                if law.pheno and law.pheno == sel_fp_pheno:
                                    if var not in mt_sub_fp_var_law_dict:
                                        mt_sub_fp_var_law_dict[var] = [law]
                                    if law not in mt_sub_fp_var_law_dict[var]:
                                        mt_sub_fp_var_law_dict[var].append(law)

                # TODO: biphasic system
                listed_laws = []
                listed_laws.append(ac_law)
                for laws in fp_var_law_dict.values():
                    listed_laws.extend(laws)
                for laws in mt_var_law_dict.values():
                    listed_laws.extend(laws)
                for laws in mt_sub_fp_var_law_dict.values():
                    listed_laws.extend(laws)
                vars = []
                for law in listed_laws:
                    for var in law.vars:
                        if var not in vars and var.cls != 'StateVariable':
                            vars.append(var)

                for var_cls in ['Structure', 'Physics', 'MassTransport', 'Flow']:
                    sec = [' ' + c.lower() if c.isupper() else c for c in var_cls]
                    sec = ''.join(sec).strip()
                    if sec in cand_config['process']['parameter']:
                        sec_dict = {
                            k: v
                            for k, v in cand_config['process']['parameter']
                            [sec].items() if k in vars
                        }
                        if not sec_dict:
                            del cand_config['process']['parameter'][sec]
                        else:
                            cand_config['process']['parameter'][sec] = sec_dict

                out_proc_cfg_path = os.path.join(out_proc_dir, f'proc_{cand_idx}.yaml')
                with open(out_proc_cfg_path, 'w') as f:
                    yaml.dump(cand_config, f, sort_keys=False)
                cand_idx += 1
