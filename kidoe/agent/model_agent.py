    def suggest(
        self,
        model_path: str,
        proc_config: dict,
        dataset: DataFrame,
        num_experiments: int | None = None,
        **kwargs,
    ) -> DataFrame:
        """Suggest experimental conditions.

        This method generates candidate experimental conditions from design parameters,
        simulates the model for all combinations, evaluates them against objectives,
        and selects experiments using the specified acquisition method.

        Args:
            model_path (str): Model directory path
            proc_config (dict): Parameterized process configuration
            dataset (DataFrame): Experiment dataset
            num_experiments (int | None): Maximum number of experiments to suggest.
                                          If None, returns all ranked candidates.

        Returns:
            DataFrame: Suggested experimental conditions
        """
        cand_param_dict = proc_config['process']['parameter']['design']
        cand_param_vals = []
        for param_dict in cand_param_dict.values():
            if 'min' in param_dict and 'max' in param_dict and 'num' in param_dict:
                min_val = param_dict['min']
                max_val = param_dict['max']
                num = param_dict['num']
                cand_param_vals.append(np.linspace(min_val, max_val, num).tolist())
            if 'val' in param_dict:
                cand_param_vals.append([param_dict['val']])
        cand_data_points = list(itertools.product(*cand_param_vals))
        cand_dataset = pd.DataFrame(cand_data_points, columns=cand_param_dict.keys())
        cand_dataset = cand_dataset.round(6)

        rmses = []
        cand_datasets = []
        for model_dir in os.listdir(model_path):
            chem_index, proc_index = model_dir.split('_', maxsplit=1)
            chem_path = os.path.join(model_path, model_dir, f'chem_{chem_index}.yaml')
            proc_path = os.path.join(model_path, model_dir, f'proc_{proc_index}.yaml')
            with open(chem_path) as f:
                _chem_config = yaml.load(f, yaml.FullLoader)
            with open(proc_path) as f:
                _proc_config = yaml.load(f, yaml.FullLoader)
            sim_dataset = self.simulate(_chem_config, _proc_config, dataset)
            error = []
            config_meas_dict = self._read_meas_param(proc_config)
            for i in range(len(dataset)):
                error.append([])
                for param_dict in config_meas_dict.values():
                    param_name = param_dict['name']
                    real = sim_dataset.loc[i, param_name].item()
                    pred = sim_dataset.loc[i, f'{param_name}(sim)'].item()
                    error[-1].append(real - pred)
            rmses.append(np.sqrt(np.square(np.array(error)).mean()).item())

            cand_dataset = self.simulate(_chem_config, _proc_config, cand_dataset)
            dataset_rows = [
                tuple(r) for i, r in dataset[cand_param_dict.keys()].iterrows()
            ]
            keep_row_idx = [
                i for i, row in cand_dataset[cand_param_dict.keys()].iterrows()
                if tuple(row) not in dataset_rows
            ]
            cand_dataset = cand_dataset.iloc[keep_row_idx]
            cand_dataset.reset_index(inplace=True, drop=True)

            design_names = [k for k, v in cand_param_dict.items() if 'val' not in v]
            obj_names = list(proc_config['process']['objective'].keys())
            x = dataset[design_names].to_numpy()
            scaler_x = MinMaxScaler()
            x = scaler_x.fit_transform(x)
            gp = GaussianProcessRegressor(kernel=Matern())
            for obj_name in obj_names:
                y = dataset[obj_name] - sim_dataset[f'{obj_name}(sim)'].to_numpy()
                gp.fit(x, y)
                cand_x = cand_dataset[design_names].to_numpy()
                cand_x = scaler_x.transform(cand_x)
                gp_mean, gp_std = gp.predict(cand_x, return_std=True)
                cand_dataset[f'{obj_name}(gp mean)'] = gp_mean
                cand_dataset[f'{obj_name}(gp std)'] = gp_std
            cand_datasets.append(cand_dataset)

        acq = proc_config['process']['algorithm']['acquisition']
        obj_dict = proc_config['process']['objective']
        sug_dataset = self._sample(acq, dataset, cand_datasets, rmses, obj_dict,
                                   num_experiments, **kwargs)
        return sug_dataset
