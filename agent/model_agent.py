    def calibrate(
        self,
        chem_config: Dict,
        proc_config: Dict,
        dataset: DataFrame,
        fast_reaction: bool = False,
        njit: bool = False,
    ) -> Tuple[Dict, float]:
        """Calibrate model parameters based on experimental data.

        This method calibrates chemistry and process configuration parameters to fit
        the provided dataset by optimizing the model to minimize differences between
        simulated and measured values.

        Args:
            chem_config (Dict): Parameterised chemistry configuration containing
                                kinetic parameters to be calibrated
            proc_config (Dict): Parameterised process configuration containing mass
                                transfer parameters to be calibrated
            dataset (DataFrame): Experimental dataset containing measured values

        Returns:
            Tuple[Dict, float]:
                Calibrated kinetic and mass transfer parameters.
                Target value after optimization.
        """
        chem_config = deepcopy(chem_config)
        proc_config = deepcopy(proc_config)
        dataset = dataset.copy()

        oper_param_config_dict = self._extract_proc_oper_param(proc_config)
        oper_param_data_dicts = []
        for i in range(len(dataset)):
            oper_param_data_dict = {}
            for param, param_dict in oper_param_config_dict.items():
                transform = param_dict['transform']
                for key, val in dataset.loc[i].items():
                    transform = transform.replace(key, str(val))
                oper_param_data_dict[param] = eval(transform)
            oper_param_data_dicts.append(oper_param_data_dict)

        meas_param_config_dict = self._extract_proc_meas_param(proc_config)
        meas_param_data_dicts = []
