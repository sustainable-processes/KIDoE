    def _extract_chem_param(self, chem_config: Dict) -> Dict:
        chem_config = deepcopy(chem_config)
        param_dict = {}

        rxns = []
        rxns.extend(chem_config['chemistry']['reaction']['main'])
        if chem_config['chemistry']['reaction']['side']:
            rxns.extend(chem_config['chemistry']['reaction']['side'])

        for rxn in rxns:
            lhs = rxn.split(' > ')[0]
            rhs = rxn.split(' > ')[1]
            lhs_spcs = [s.split(' ')[-1] for s in lhs.split(' + ')]
            rhs_spcs = [s.split(' ')[-1] for s in rhs.split(' + ')]
            for s in lhs.split(' + '):
                if re.match(r'^\d+$', s.split(' ')[0]):
                    val = {'unit': None, 'val': -float(s.split(' ')[0])}
                    spc = s.split(' ')[1]
                else:
                    val = {'unit': None, 'val': -1.0}
                    spc = s
                key = ('Stoichiometric_Coefficient', None, None, rxn, spc)
                if spc in rhs_spcs:
                    continue
                param_dict[key] = val
            for s in rhs.split(' + '):
                if re.match(r'^\d+$', s.split(' ')[0]):
                    val = {'unit': None, 'val': float(s.split(' ')[0])}
                    spc = s.split(' ')[1]
                else:
                    val = {'unit': None, 'val': 1.0}
                    spc = s
                key = ('Stoichiometric_Coefficient', None, None, rxn, spc)
                if spc in lhs_spcs:
                    continue
                param_dict[key] = val

        if 'constant' in chem_config['chemistry']['parameter']:
            config_constant_dict = chem_config['chemistry']['parameter']['constant']
            if config_constant_dict:
                for param in config_constant_dict:
                    ind = (param, None, None, None, None)
                    val = config_constant_dict[param]['val']
                    param_dict[ind] = val

        for rxn in chem_config['chemistry']['parameter']:
            if rxn == 'constant':
                continue
            config_reaction_dict = chem_config['chemistry']['parameter'][rxn]
            for param in config_reaction_dict:
                param_dims = set(self.entity['var'][param]['dims'])
                if param_dims == set(['Reaction']):
                    ind = (param, None, None, rxn, None)
                    val = config_reaction_dict[param]
                    param_dict[ind] = val
                if param_dims == set(['Reaction', 'Species']):
                    for spc in config_reaction_dict[param]:
                        ind = (param, None, None, rxn, spc)
                        val = config_reaction_dict[param][spc]
                        param_dict[ind] = val
                if param_dims == set(['Stream', 'Reaction']):
                    for stm in config_reaction_dict[param]:
                        ind = (param, None, stm, rxn, None)
                        val = config_reaction_dict[param][stm]
                        param_dict[ind] = val

        param_dict = dict(sorted(param_dict.items()))
        return param_dict

    def _extract_proc_param(self, proc_config: Dict) -> Dict:
        proc_config = deepcopy(proc_config)
        param_dict = {}
        for sec in ['structure', 'physics', 'mass transport']:
            if sec not in proc_config['process']['parameter']:
                continue
            config_sec_dict = proc_config['process']['parameter'][sec]
            for param in config_sec_dict:
                param_dims = set(self.entity['var'][param]['dims'])
                if param_dims == set([]):
                    ind = (param, None, None, None, None)
                    val = config_sec_dict[param]
                    param_dict[ind] = val
                if param_dims == set(['Species']):
                    for spc in config_sec_dict[param]:
                        ind = (param, None, None, None, spc)
                        val = config_sec_dict[param][spc]
                        param_dict[ind] = val
                if param_dims == set(['Stream']):
                    for stm in config_sec_dict[param]:
                        ind = (param, None, stm, None, None)
                        val = config_sec_dict[param][stm]
                        param_dict[ind] = val
                if param_dims == set(['Stream', 'Species']):
                    for stm in config_sec_dict[param]:
                        for spc in config_sec_dict[param][stm]:
                            ind = (param, None, stm, None, spc)
                            val = config_sec_dict[param][stm][spc]
                            param_dict[ind] = val
        param_dict = dict(sorted(param_dict.items()))
        return param_dict

