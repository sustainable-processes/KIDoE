    def simulate(self, chem_config: dict, proc_config: dict,
                 dataset: DataFrame) -> DataFrame:
        """Simulate model based on given chemistry and process configurations.
        
        This method simulates a chemical process based on chemistry and process 
        configurations on the provided operation dataset. Output columns including
        measurement and optimisation targets will be added to the dataset.

        Args:
            chem_config (dict): Input chemistry config
            proc_config (dict): Input process config
            dataset (DataFrame): Input dataset for simulation
        Returns:
            DataFrame: Simulation results
        """
        dataset = dataset.copy()
        config_oper_dict = self._read_oper_param(proc_config)
        oper_param_dicts = []
        for i in range(len(dataset)):
            oper_param_dict = {}
            for param, param_dict in config_oper_dict.items():
                transform = param_dict['transform']
                for key, val in dataset.iloc[i].items():
                    transform = transform.replace(key, str(val))
                oper_param_dict[param] = round(eval(transform), 6)
            oper_param_dicts.append(oper_param_dict)

        param_dict = self._read_val_param(chem_config, proc_config)
        model_code = self._generate_model_code(chem_config, proc_config)

        with tempfile.TemporaryDirectory() as temp_dir:
            with open(os.path.join(temp_dir, 'simulate.py'), 'w') as f:
                f.write(model_code)
                f.write('\n\n')
                f.write('param_dict = {\n')
                for k, v in param_dict.items():
                    if k in oper_param_dicts[0]:
                        v = None
                    f.write(f'    {k!s}: {v}, \n')
                f.write('}\n')
                f.write('oper_param_dicts = [\n')
                for oper_param_dict in oper_param_dicts:
                    f.write(f'    {oper_param_dict}, \n')
                f.write(']\n')
                f.write('param_dicts = []\n')
                f.write('for oper_param_dict in oper_param_dicts:\n')
                f.write('    _param_dict = param_dict.copy()\n')
                f.write('    _param_dict.update(oper_param_dict)\n')
                f.write('    param_dicts.append(_param_dict)\n\n')
                f.write('if __name__ == \'__main__\':\n')
                f.write('    import os\n')
                f.write('    import pickle\n')
                f.write('    import multiprocessing as mp\n')
                f.write('    mp.set_start_method(\'fork\')\n')
                f.write('    _ = simulate(param_dicts[0])\n')
                f.write('    with mp.Pool(8) as pool:\n')
                f.write('        res = pool.map(simulate, param_dicts)\n')
                f.write('        pickle.dump(res, open(os.path.join('
                        'os.path.dirname(__file__), \'res.pkl\'), \'wb\'))\n')
            with open(os.path.join(temp_dir, 'simulate.py'), 'r') as f:
                print(''.join(f.readlines()))
                exit(0)
            os.system(f'python {temp_dir}/simulate.py')
            with open(f'{temp_dir}/res.pkl', 'rb') as f:
                res = pickle.load(f)

        meas_param_dict = self._read_meas_param(proc_config)
        for param, param_dict in meas_param_dict.items():
            param_name = param_dict['name']
            param_vals = [round(float(r[param]), 6) for r in res]
            dataset[f'{param_name}(sim)'] = param_vals
        for obj_name, obj_dict in proc_config['process']['objective'].items():
            obj_vals = []
            for i in range(len(dataset)):
                transform = obj_dict['transform']
                for key in proc_config['process']['parameter']['design']:
                    val = dataset.loc[i, key]
                    transform = transform.replace(key, str(val))
                for param_dict in meas_param_dict.values():
                    key = param_dict['name']
                    val = dataset.loc[i, f'{key}(sim)']
                    transform = transform.replace(key, str(val))
                obj_vals.append(round(float(eval(transform)), 6))
            dataset[f'{obj_name}(sim)'] = obj_vals
        return dataset

