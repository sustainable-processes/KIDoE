import os
import shutil
from typing import Dict

import yaml

from .knowledge_graph_agent import KnowledgeGraphAgent


class ProcessAgent:
    """Process agent for generating process configurations.
    
    Phenomena are candidate observations defined in the Model Ontology.
    Parameters are generated by navigating the Model Ontology graph.

    Example:
        # TODO
    """

    def __init__(self):
        super().__init__()
        ontomo_path = os.path.join(os.path.abspath(__file__),
                                   '../../ontology/OntoMo.owl')
        self.ontomo = KnowledgeGraphAgent(ontomo_path)
        self.entity = self.ontomo.query()

    def parameterize(self, proc_config: Dict, chem_config: Dict) -> Dict:
        """Parameterize process configuration based on the Model Ontology.

        Args:
            proc_config (Dict): Process configuration containing defined phenomena
            chem_config (Dict): Base chemistry configuration

        Returns:
            Dict: Updated process configuration with parameters
        """
        ac_pheno = proc_config['process']['phenomenon']['accumulation']

        fp_phenos = proc_config['process']['phenomenon']['flow pattern']
        if isinstance(fp_phenos, str):
            fp_phenos = [fp_phenos]

        mt_phenos = proc_config['process']['phenomenon']['mass transport']
        if isinstance(mt_phenos, str):
            mt_phenos = [mt_phenos]

        ac_fp_phenos = self.entity['pheno'][ac_pheno]['fps']
        fp_phenos = [pheno for pheno in fp_phenos if pheno in ac_fp_phenos]
        fp_mt_phenos = []
        for fp_pheno in fp_phenos:
            for mt_pheno in self.entity['pheno'][fp_pheno]['mts']:
                if mt_pheno not in fp_mt_phenos:
                    fp_mt_phenos.append(mt_pheno)
        mt_phenos = [pheno for pheno in mt_phenos if pheno in fp_mt_phenos]

        ac_laws = []
        for law, law_dict in self.entity['law'].items():
            if law_dict['pheno'] == ac_pheno:
                ac_laws.append(law)
        ac_law = ac_laws[0]

        fp_param_law_dict = {}
        for param in self.entity['law'][ac_law]['vars']:
            for param_law in self.entity['var'][param]['laws']:
                if self.entity['law'][param_law]['pheno'] in fp_phenos:
                    if param not in fp_param_law_dict:
                        fp_param_law_dict[param] = [param_law]
                    if param_law not in fp_param_law_dict[param]:
                        fp_param_law_dict[param].append(param_law)

        mt_param_law_dict = {}
        for param in self.entity['law'][ac_law]['opt_vars']:
            for param_law in self.entity['var'][param]['laws']:
                if self.entity['law'][param_law]['pheno'] in mt_phenos:
                    if param not in mt_param_law_dict:
                        mt_param_law_dict[param] = [param_law]
                    if param_law not in mt_param_law_dict[param]:
                        mt_param_law_dict[param].append(param_law)

        mt_sub_fp_param_law_dict = {}
        for mt_laws in mt_param_law_dict.values():
            for mt_law in mt_laws:
                for param in self.entity['law'][mt_law]['vars']:
                    for param_law in self.entity['var'][param]['laws']:
                        if self.entity['law'][param_law]['pheno'] in fp_phenos:
                            if param not in mt_sub_fp_param_law_dict:
                                mt_sub_fp_param_law_dict[param] = [param_law]
                            if param_law not in mt_sub_fp_param_law_dict[param]:
                                mt_sub_fp_param_law_dict[param].append(param_law)

        # TODO: biphasic system
        reagents = list(chem_config['chemistry']['species']['reagents'].keys())
        products = list(chem_config['chemistry']['species']['products'].keys())
        spcs = [
            spc for role in chem_config['chemistry']['species']
            if chem_config['chemistry']['species'][role]
            for spc in chem_config['chemistry']['species'][role]
        ]
        stms = list(proc_config['process']['inlet'].keys())
        listed_laws = []
        listed_laws.append(ac_law)
        for laws in fp_param_law_dict.values():
            listed_laws.extend(laws)
        for laws in mt_param_law_dict.values():
            listed_laws.extend(laws)
        for laws in mt_sub_fp_param_law_dict.values():
            listed_laws.extend(laws)
        params = []
        for law in listed_laws:
            for param in self.entity['law'][law]['vars']:
                if self.entity['var'][param]['cls'] == 'StateVariable':
                    continue
                if param not in params:
                    params.append(param)

        proc_config['process']['parameter'] = {}
        for param_cls in ['Structure', 'Physics', 'MassTransport']:
            sec = ''.join([' ' + c.lower() if c.isupper() else c for c in param_cls])
            sec = sec.strip()
            for param in params:
                param_dict = self.entity['var'][param]
                if param_dict['laws']:
                    continue
                if param_dict['cls'] == f'{param_cls}Parameter':
                    if sec not in proc_config['process']['parameter']:
                        proc_config['process']['parameter'][sec] = {}
                    config_param_dict = {}
                    if set(param_dict['dims']) == set([]):
                        config_param_dict = {
                            'unit': param_dict['unit'],
                            'val': None
                        }
                    if set(param_dict['dims']) == set(['Species']):
                        for spc in spcs:
                            config_param_dict[spc] = {
                                'unit': param_dict['unit'],
                                'val': None
                            }
                    if set(param_dict['dims']) == set(['Stream', 'Species']):
                        for stm in stms:
                            config_param_dict[stm] = {}
                            for spc in spcs:
                                config_param_dict[stm][spc] = {
                                    'unit': param_dict['unit'],
                                    'val': None
                                }
                    proc_config['process']['parameter'][sec][param] = config_param_dict

        sec = 'operation'
        for param in params + ['Temperature']:
            # Temperature is always included for reaction rates
            param_dict = self.entity['var'][param]
            if param_dict['laws']:
                continue
            config_param_dict = {}
            if param_dict['cls'] == 'OperationParameter':
                if sec not in proc_config['process']['parameter']:
                    proc_config['process']['parameter'][sec] = {}
                config_param_dict = {}
                if set(param_dict['dims']) == set([]):
                    config_param_dict = {
                        'unit': param_dict['unit'],
                        'name': None,
                        'transform': None,
                    }
                if set(param_dict['dims']) == set(['Stream']):
                    for stm in stms:
                        config_param_dict[stm] = {
                            'unit': param_dict['unit'],
                            'name': None,
                            'transform': None,
                        }
                if set(param_dict['dims']) == set(['Stream', 'Species']):
                    for stm in stms:
                        config_param_dict[stm] = {}
                        for spc in reagents:
                            config_param_dict[stm][spc] = {
                                'unit': param_dict['unit'],
                                'name': None,
                                'transform': None,
                            }
                proc_config['process']['parameter'][sec][param] = config_param_dict
        proc_config['process']['parameter']['design'] = None

        sec = 'measure'
        param = 'Outlet_Concentration'
        proc_config['process']['parameter'][sec] = {}
        config_param_dict = {}
        for stm in stms:
            config_param_dict[stm] = {}
            for spc in products:
                config_param_dict[stm][spc] = {
                    'unit': 'mol_per_L',
                    'name': None
                }
        proc_config['process']['parameter']['measure'][param] = config_param_dict
        proc_config['process']['algorithm'] = {'acquisition': 'enumeration'}
        proc_config['process']['objective'] = {
            'yield': {
                'transform': None,
                'target': 'max'
            }
        }
        return proc_config

    def parameterize_and_dump(
        self, in_proc_cfg_path: str, chem_cfg_path: str, out_proc_cfg_path: str):
        """Load configuration files, parameterize, and save the result.

        Reads process and chemistry configuration files, generates process 
        parameters using the Model Ontology, and writes the parameterized 
        configuration to an output file.

        Args:
            in_proc_cfg_path (str): Path to input process configuration file
            chem_cfg_path (str): Path to input chemistry configuration file
            out_proc_cfg_path (str): Path to output parameterized process 
                                     configuration file
        """
        proc_config = yaml.load(open(in_proc_cfg_path), yaml.FullLoader)
        chem_config = yaml.load(open(chem_cfg_path), yaml.FullLoader)
        proc_config = self.parameterize(proc_config, chem_config)
        yaml.dump(proc_config, open(out_proc_cfg_path, 'w'), sort_keys=False)

    def generate_and_dump(self, in_proc_cfg_path: str, out_proc_dir: str):
        """Generate and save candidate process configurations.

        This method generates multiple candidate process configurations by enumerating
        all valid phenomenon combinations using the Model Ontology. Each candidate 
        configuration contains only parameters relevant to that combination.

        Args:
            in_proc_cfg_path (str): Path to input process configuration file
            out_proc_dir (str): Directory where candidate configurations will be saved
        """
        if os.path.exists(out_proc_dir):
            while True:
                delete_flag = input(f'Delete files in "{out_proc_dir}"? (y/n)')
                if delete_flag in ['Y', 'y', '']:
                    for filename in os.listdir(out_proc_dir):
                        file_path = os.path.join(out_proc_dir, filename)
                        if os.path.isfile(file_path) or os.path.islink(file_path):
                            os.unlink(file_path)
                        elif os.path.isdir(file_path):
                            shutil.rmtree(file_path)
                    break
                elif delete_flag in ['N', 'n']:
                    exit(0)
        else:
            os.mkdir(out_proc_dir)

        config = yaml.load(open(in_proc_cfg_path), yaml.FullLoader)
        ac_pheno = config['process']['phenomenon']['accumulation']
        fp_phenos = config['process']['phenomenon']['flow pattern']
        if isinstance(fp_phenos, str):
            fp_phenos = [fp_phenos]
        mt_phenos = config['process']['phenomenon']['mass transport']
        if isinstance(mt_phenos, str):
            mt_phenos = [mt_phenos]

        ac_fp_phenos = self.entity['pheno'][ac_pheno]['fps']
        fp_phenos = [pheno for pheno in fp_phenos if pheno in ac_fp_phenos]
        fp_mt_phenos = []
        for fp_pheno in fp_phenos:
            for mt_pheno in self.entity['pheno'][fp_pheno]['mts']:
                if mt_pheno not in fp_mt_phenos:
                    fp_mt_phenos.append(mt_pheno)
        mt_phenos = [pheno for pheno in mt_phenos if pheno in fp_mt_phenos]

        cand_idx = 0
        for sel_fp_pheno in fp_phenos:
            for sel_mt_pheno in mt_phenos:
                if sel_mt_pheno not in self.entity['pheno'][sel_fp_pheno]['mts']:
                    continue
                sel_mt_phenos = [sel_mt_pheno]
                cand_config = config.copy()
                cand_config['process']['phenomenon']['flow pattern'] = sel_fp_pheno
                cand_config['process']['phenomenon']['mass transport'] = sel_mt_phenos

                ac_laws = []
                for law, law_dict in self.entity['law'].items():
                    if law_dict['pheno'] == ac_pheno:
                        ac_laws.append(law)
                ac_law = ac_laws[0]

                fp_param_law_dict = {}
                for param in self.entity['law'][ac_law]['vars']:
                    for param_law in self.entity['var'][param]['laws']:
                        law_pheno = self.entity['law'][param_law]['pheno']
                        if law_pheno != sel_fp_pheno:
                            continue
                        if param not in fp_param_law_dict:
                            fp_param_law_dict[param] = [param_law]
                        if param_law not in fp_param_law_dict[param]:
                            fp_param_law_dict[param].append(param_law)

                mt_param_law_dict = {}
                for param in self.entity['law'][ac_law]['vars']:
                    for param_law in self.entity['var'][param]['laws']:
                        law_pheno = self.entity['law'][param_law]['pheno']
                        if law_pheno not in sel_mt_phenos:
                            continue
                        if param not in mt_param_law_dict:
                            mt_param_law_dict[param] = [param_law]
                        if param_law not in mt_param_law_dict[param]:
                            mt_param_law_dict[param].append(param_law)

                mt_sub_fp_param_law_dict = {}
                for mt_laws in mt_param_law_dict.values():
                    for mt_law in mt_laws:
                        for param in self.entity['law'][mt_law]['vars']:
                            for param_law in self.entity['var'][param]['laws']:
                                law_pheno = self.entity['law'][param_law]['pheno']
                                if law_pheno != sel_fp_pheno:
                                    continue
                                if param not in mt_sub_fp_param_law_dict:
                                    mt_sub_fp_param_law_dict[param] = [param_law]
                                if param_law not in mt_sub_fp_param_law_dict[param]:
                                    mt_sub_fp_param_law_dict[param].append(param_law)

                # TODO: biphasic system
                listed_laws = []
                listed_laws.append(ac_law)
                for laws in fp_param_law_dict.values():
                    listed_laws.extend(laws)
                for laws in mt_param_law_dict.values():
                    listed_laws.extend(laws)
                for laws in mt_sub_fp_param_law_dict.values():
                    listed_laws.extend(laws)
                params = []
                for law in listed_laws:
                    for param in self.entity['law'][law]['vars']:
                        if param not in params:
                            params.append(param)

                for param_cls in ['Structure', 'Physics', 'MassTransport']:
                    sec = ''.join(
                        [' ' + c.lower() if c.isupper() else c for c in param_cls])
                    sec = sec.strip()
                    if sec in cand_config['process']['parameter']:
                        sec_dict = {
                            k: v
                            for k, v in cand_config['process']['parameter']
                            [sec].items() if k in params
                        }
                        if sec_dict:
                            cand_config['process']['parameter'][sec] = sec_dict

                out_proc_cfg_path = os.path.join(out_proc_dir, f'proc_{cand_idx}.yaml')
                yaml.dump(cand_config, open(out_proc_cfg_path, 'w'), sort_keys=False)
                cand_idx += 1
