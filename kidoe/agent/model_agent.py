    def calibrate(self, chem_config: dict, proc_config: dict,
                  dataset: DataFrame) -> tuple[dict, float]:
        """Calibrate model parameters based on experimental data.

        This method calibrates chemistry and process configuration parameters to fit
        the provided dataset by optimizing the model to minimize differences between
        simulated and measured values.

        Args:
            chem_config (dict): Parameterised chemistry configuration containing
                                kinetic parameters to be calibrated
            proc_config (dict): Parameterised process configuration containing mass
                                transfer parameters to be calibrated
            dataset (DataFrame): Experimental dataset containing measured values

        Returns:
            tuple[dict, float]:
                Calibrated kinetic and mass transfer parameters and optimization loss 
                after optimization.
        """
        chem_config = deepcopy(chem_config)
        proc_config = deepcopy(proc_config)
        dataset = dataset.copy()

        config_oper_dict = self._read_oper_param(proc_config)
        oper_param_dicts = []
        for i in range(len(dataset)):
            oper_param_dict = {}
            for param, param_dict in config_oper_dict.items():
                transform = param_dict['transform']
                for key, val in dataset.iloc[i].items():
                    transform = transform.replace(key, str(val))
                oper_param_dict[param] = round(eval(transform), 6)
            oper_param_dicts.append(oper_param_dict)

        config_meas_dict = self._read_meas_param(proc_config)
        meas_param_dicts = []
        for i in range(len(dataset)):
            meas_param_dict = {}
            for param, param_dict in config_meas_dict.items():
                param_name = param_dict['name']
                meas_param_dict[param] = dataset.loc[i, param_name].item()
            meas_param_dicts.append(meas_param_dict)

        config_cal_dict = self._read_cal_param(chem_config, proc_config)
        param_dict = self._read_val_param(chem_config, proc_config)
        model_code = self._generate_model_code(chem_config, proc_config)

        with tempfile.TemporaryDirectory() as temp_dir:
            with open(os.path.join(temp_dir, 'calibrate.py'), 'w') as f:
                f.write(model_code)
                f.write('\n\n')
                f.write('param_dict = {\n')
                for k, v in param_dict.items():
                    if k in config_cal_dict or k in config_oper_dict:
                        v = None
                    f.write(f'    {k!s}: {v}, \n')
                f.write('}\n')
                f.write('oper_param_dicts = [\n')
                for oper_param_dict in oper_param_dicts:
                    f.write(f'    {oper_param_dict}, \n')
                f.write(']\n')
                f.write('param_dicts = []\n')
                f.write('for oper_param_dict in oper_param_dicts:\n')
                f.write('    _param_dict = param_dict.copy()\n')
                f.write('    _param_dict.update(oper_param_dict)\n')
                f.write('    param_dicts.append(_param_dict)\n\n')
                f.write('meas_param_dicts = [\n')
                for meas_param_dict in meas_param_dicts:
                    f.write(f'    {meas_param_dict}, \n')
                f.write(']\n\n')
                f.write('cal_param_dict = {\n')
                for k, v in config_cal_dict.items():
                    f.write(f'    {k!s}: {v}, \n')
                f.write('}\n\n')
                f.writelines([
                    'def calc_error(p):\n',
                    '    errors = []\n',
                    '    reals = []\n',
                    '    for param_dict, meas_param_dict in zip(param_dicts, meas_param_dicts):\n',
                    '        error = []\n',
                    '        real = []\n',
                    '        for key, val in zip(cal_param_dict.keys(), p):\n',
                    '            param_dict[key] = val\n',
                    '        res = simulate(param_dict)\n',
                    '        for key, val in res.items():\n',
                    '            if key in meas_param_dict:\n',
                    '                error.append(meas_param_dict[key] - val)\n',
                    '                real.append(meas_param_dict[key])\n',
                    '        errors.append(error)\n',
                    '        reals.append(real)\n',
                ])
                if self.err == 'rmse':
                    f.write(
                        '    return np.sqrt(np.square(np.array(errors)).mean()).item()\n\n'
                    )
                if self.err == 'rmsre':
                    f.write(
                        '    return np.sqrt(np.square(np.array(errors) / (np.array(reals) + 1e-6)).mean()).item()\n\n'
                    )
                f.write("if __name__ == '__main__':\n")
                f.write('    import os\n')
                f.write('    import pickle\n')
                f.write('    import multiprocessing as mp\n')
                f.write("    mp.set_start_method('fork')\n")
                f.write(
                    "    cal_param_bounds = [(v['min'], v['max']) for v in cal_param_dict.values()]\n"
                )
                f.write('    p = [np.mean(b).item() for b in cal_param_bounds]\n')
                f.write('    param_dict = param_dicts[0]\n')
                f.write('    for key, val in zip(cal_param_dict.keys(), p):\n')
                f.write('        param_dict[key] = val\n')
                f.write('    simulate(param_dict)\n')
                f.write(
                    f"    res = differential_evolution(calc_error, bounds=cal_param_bounds, maxiter={self.maxiter}, popsize=16, workers=16, updating='deferred', polish=False, disp=True)\n"
                )
                f.write(
                    "    pickle.dump(res, open(os.path.join(os.path.dirname(__file__), 'res.pkl'), 'wb'))\n"
                )
            # with open(os.path.join(temp_dir, 'calibrate.py'), 'r') as f:
            #     print(''.join(f.readlines()))
            #     sys.exit(0)
            os.system(f'python {temp_dir}/calibrate.py')
            with open(f'{temp_dir}/res.pkl', 'rb') as f:
                res = pickle.load(f)

        for key, val in zip(config_cal_dict.keys(), res.x):
            config_cal_dict[key]['val'] = float(f'{val.item():.6g}')
        return config_cal_dict, res.fun

