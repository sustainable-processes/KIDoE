    def _add_simulate_param_setup(
        self,
        modeler: NumpyModeler,
        ac_law: Law,
        param_dict: dict,
        dim_dict: dict,
    ):
        stms, spcs = dim_dict['stm'], dim_dict['spc']
        nstm, nspc = len(stms), len(spcs)
        modeler.add_code('# parameter setup', 1)
        modeler.add_code('p = np.array(list(param_dict.values()))', 1)
        param_inds = list(param_dict.keys())
        if ac_law.pheno == 'Continuous':
            vars = [ac_law.int_ul_var, ac_law.init_val]
        if ac_law.pheno == 'CSTR':
            vars = [ac_law.init_val]
        for var in vars:
            sym = MMLExpr(var.sym).to_numpy()
            if set(var.dims) == set([]):
                ind = (var, None, None, None, None)
                modeler.add_code(f'{sym} = p[{param_inds.index(ind)}]', 1)
            if set(var.dims) == set(['Stream', 'Species']):
                modeler.add_code(f'{sym} = np.zeros({nstm, nspc}, dtype=np.float64)', 1)
                for stm, spc in itertools.product(stms, spcs):
                    stm_i = stms.index(stm)
                    spc_i = spcs.index(spc)
                    ind = (var, None, stm, None, spc)
                    if ind in param_inds:
                        param_i = param_inds.index(ind)
                        modeler.add_code(f'{sym}[{stm_i},{spc_i}] = p[{param_i}]', 1)
            unit = var.unit
            if unit:
                if unit.mtr and unit.rto:
                    modeler.add_code(f'{sym} *= {unit.rto}', 1)
                if unit.mtr and unit.intcpt:
                    modeler.add_code(f'{sym} += {unit.intcpt}', 1)

