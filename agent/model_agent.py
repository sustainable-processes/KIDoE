    def suggest_with_single_model(
        self,
        chem_config: Dict,
        proc_config: Dict,
        dataset: DataFrame,
        num_experiments: int | None = None,
        fast_reaction: bool = False,
        njit: bool = False,
        **kwargs,
    ) -> DataFrame:
        """Suggest experimental conditions using single model.

        This method generates candidate experimental conditions from design parameters,
        simulates the model for all combinations, evaluates them against objectives,
        and selects experiments using the specified acquisition method.

        Args:
            chem_config (Dict): Calibrated chemistry configuration
            proc_config (Dict): Calibrated process configuration
            dataset (DataFrame): Sampled points in experiments
            num_experiments (int | None): Maximum number of experiments to suggest.
                                          If None, returns all ranked candidates.

        Returns:
            DataFrame: Suggested experimental conditions with prediction
        """
        dataset = dataset.copy()
        meas_param_config_dict = self._extract_proc_meas_param(proc_config)
        for obj_name, obj_dict in proc_config['process']['objective'].items():
            obj_vals = []
            for i in range(len(dataset)):
                transform = obj_dict['transform']
                for key in proc_config['process']['parameter']['design']:
                    val = dataset.loc[i, key]
                    transform = transform.replace(key, str(val))
                for param_dict in meas_param_config_dict.values():
                    key = param_dict['name']
                    val = dataset.loc[i, key]
                    transform = transform.replace(key, str(val))
                obj_vals.append(float(f'{eval(transform)}'))
            dataset[obj_name] = obj_vals

        cand_param_dict = proc_config['process']['parameter']['design']
        cand_param_vals = []
        for param_dict in cand_param_dict.values():
            if 'min' in param_dict and 'max' in param_dict and 'num' in param_dict:
                min_val = param_dict['min']
                max_val = param_dict['max']
                num = param_dict['num']
                cand_param_vals.append(np.linspace(min_val, max_val, num).tolist())
            if 'val' in param_dict:
                cand_param_vals.append([param_dict['val']])
        cand_data_points = list(itertools.product(*cand_param_vals))
        cand_dataset = pd.DataFrame(cand_data_points, columns=cand_param_dict.keys())

        cand_dataset = self.simulate(
            chem_config,
            proc_config,
            cand_dataset,
            fast_reaction=fast_reaction,
            njit=njit,
        )
        dataset_rows = [tuple(r) for i, r in dataset[cand_param_dict.keys()].iterrows()]
        keep_row_idx = [
            i
            for i, row in cand_dataset[cand_param_dict.keys()].iterrows()
            if tuple(row) not in dataset_rows
        ]
        cand_dataset = cand_dataset.iloc[keep_row_idx]
        cand_dataset.to_csv('test.csv')
        acq = proc_config['process']['algorithm']['acquisition']
        obj_dict = proc_config['process']['objective']
        sug_dataset = self._sample(
            acq, dataset, cand_dataset, obj_dict, num_experiments, **kwargs
        )
        return sug_dataset

